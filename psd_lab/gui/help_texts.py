def metric(label: str):
    """Пояснение к полю/столбцу по подписи: «d10, мкм», «<15 мкм, %», «Обскур., %» …"""
    t = label.strip()
    base = re.split(r",\s*(мкм|%|п\.п\.|г/см³|м²/г|г)$", t)[0].strip()
    base = re.split(r",\s*(мкм|%|п\.п\.|г/см³|м²/г|г)\b", base)[0].strip()
    for k in (base, base.replace(".", "")):
        if k in METRICS:
            return METRICS[k]
    if base.lower().startswith("обскур"):
        return METRICS["Обскурация"]
    m = re.fullmatch(r"([<>])\s*([\d.,]+)(?:\s*мкм)?", base)
    if m:
        side = "мельче" if m.group(1) == "<" else "крупнее"
        return (f"Доля {side} {m.group(2)} мкм",
                f"Процент объёма порошка {side} {m.group(2)} мкм (без перенормировки).")
    m = re.fullmatch(r"([\d.,]+)\s*[–-]\s*([\d.,]+)(?:\s*мкм)?", base)
    if m:
        return (f"Доля {m.group(1)}–{m.group(2)} мкм",
                f"Процент объёма порошка с размером от {m.group(1)} до {m.group(2)} мкм — например, окно для печати.")
    return None
